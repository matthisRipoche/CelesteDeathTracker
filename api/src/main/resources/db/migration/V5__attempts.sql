-- Tentatives (une partie sur une face de map, de l'entrée à la sortie) et entrées de room.
-- Ces deux tables permettent de voir les tentatives RÉUSSIES (sans mort), ce que la table death
-- seule ne montre pas. L'identifiant client_id est un UUID fabriqué par le mod : chaque événement
-- le porte, donc l'ordre d'arrivée ou la perte d'un événement ne casse pas la reconstruction.
CREATE TABLE attempts (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    client_id              VARCHAR(36)  NOT NULL,
    chapter                VARCHAR(255) NOT NULL,
    side                   VARCHAR(1)   NOT NULL,
    save_slot              INTEGER,
    map_name               VARCHAR(255),
    started_at             BIGINT       NOT NULL,
    started_from_beginning BOOLEAN,
    start_room             VARCHAR(255),
    ended_at               BIGINT,
    end_reason             VARCHAR(30),
    end_room               VARCHAR(255),
    session_time_ms        BIGINT,
    CONSTRAINT uq_attempts_user_client UNIQUE (user_id, client_id)
);

CREATE INDEX idx_attempts_user_started ON attempts (user_id, started_at);
CREATE INDEX idx_attempts_user_map     ON attempts (user_id, chapter, side);

CREATE TABLE room_entries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id      BIGINT       NOT NULL REFERENCES attempts (id) ON DELETE CASCADE,
    room            VARCHAR(255) NOT NULL,
    entered_at      BIGINT       NOT NULL,
    session_time_ms BIGINT
);

CREATE INDEX idx_room_entries_attempt ON room_entries (attempt_id);

-- Contexte d'une mort. Nullable : les morts envoyées par l'ancien mod (ou importées) n'ont ni
-- tentative, ni face, ni sauvegarde.
ALTER TABLE death ADD COLUMN attempt_id BIGINT REFERENCES attempts (id) ON DELETE SET NULL;
ALTER TABLE death ADD COLUMN side       VARCHAR(1);
ALTER TABLE death ADD COLUMN save_slot  INTEGER;

CREATE INDEX idx_death_attempt ON death (attempt_id);
