-- Tokens d'API : un compte peut en avoir plusieurs (un par machine). On ne stocke que le hash SHA-256.
CREATE TABLE api_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash   VARCHAR(64)  NOT NULL UNIQUE,
    label        VARCHAR(100) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMP WITH TIME ZONE,
    revoked      BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_api_tokens_user ON api_tokens (user_id);

-- Propriétaire d'une mort. Nullable : les morts importées avant l'arrivée des comptes n'en ont pas
-- (elles ne sont visibles par personne).
ALTER TABLE death ADD COLUMN user_id BIGINT REFERENCES users (id) ON DELETE CASCADE;

CREATE INDEX idx_death_user_timestamp ON death (user_id, timestamp);
