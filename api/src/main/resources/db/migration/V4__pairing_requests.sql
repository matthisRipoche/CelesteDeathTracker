-- Appairage d'un jeu avec un compte, par code (comme la connexion d'une TV).
-- Le token d'API n'est JAMAIS stocké ici : il est généré au moment où le mod le récupère.
CREATE TABLE pairing_requests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Secret connu du seul mod (hash SHA-256) : il prouve que c'est bien lui qui interroge
    device_code_hash VARCHAR(64)  NOT NULL UNIQUE,
    -- Code court affiché dans le jeu et tapé par l'utilisateur sur le site (ex. K7QM4XRD)
    user_code        VARCHAR(16)  NOT NULL UNIQUE,
    status           VARCHAR(16)  NOT NULL,   -- PENDING | APPROVED | DENIED | CONSUMED
    device_name      VARCHAR(60)  NOT NULL,
    requester_ip     VARCHAR(64),
    user_id          BIGINT REFERENCES users (id) ON DELETE CASCADE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_pairing_expires ON pairing_requests (expires_at);
