-- Ne jamais modifier une migration déjà appliquée : en créer une nouvelle (V2__...).
CREATE TABLE death (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp       BIGINT       NOT NULL,
    chapter         VARCHAR(255) NOT NULL,
    room            VARCHAR(255) NOT NULL,
    death_x         INTEGER      NOT NULL,
    death_y         INTEGER      NOT NULL,
    total_deaths    INTEGER      NOT NULL,
    session_deaths  INTEGER      NOT NULL,
    time_in_room_ms BIGINT       NOT NULL
);

CREATE INDEX idx_death_chapter_room ON death (chapter, room);
CREATE INDEX idx_death_timestamp    ON death (timestamp);
